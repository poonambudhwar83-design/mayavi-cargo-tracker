import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {jepoTrackingState,jepoTrackingStatusLabel,sortJepoActiveRecords} from '../lib/jepoTrackingState.js';
import {jepoTodayIst,jepoDaysSinceBooking,jepoOverdueDays,jepoOverdueRows} from '../lib/jepoOverdue.js';
import {PDFDocument} from 'pdf-lib';
import {OVERDUE_EXPORT_COLUMNS,overdueExportData,createOverdueEditablePdfBytes} from '../lib/jepoOverdueExports.js';
const live={awb:'200',status:'IN_TRANSIT',liveStatus:'In Transit',checkedAt:'2026-11-08T02:01:00.000Z',bookingDate:'2026-11-07'};
const queued={awb:'100',status:'PENDING',liveStatus:'',checkedAt:null,trackingError:'',bookingDate:'2026-11-07'};
const failure={awb:'300',status:'PENDING',liveStatus:'',checkedAt:'2026-11-08T02:02:00.000Z',trackingError:'JEPO did not expose a verified shipment status.',bookingDate:'2026-11-06'};
const delivered={awb:'400',status:'DELIVERED',liveStatus:'Delivered',checkedAt:'2026-11-08T02:03:00.000Z'};
assert.equal(jepoTrackingState(queued),'AWAITING_FIRST_CHECK');
assert.equal(jepoTrackingStatusLabel(queued),'Awaiting First Check');
assert.equal(jepoTrackingState(failure),'RETRY_NEEDED');
assert.equal(jepoTrackingStatusLabel(failure),'Retry Needed');
assert.equal(jepoTrackingState(live),'LIVE_UPDATED');
assert.equal(jepoTrackingStatusLabel(live),'In Transit');
assert.equal(jepoTrackingState(delivered),'DELIVERED');
assert.deepEqual(sortJepoActiveRecords([queued,live,failure]).map(r=>r.awb),['300','200','100'],'No unexplained PENDING gaps in visible Active list.');
const dashboard=readFileSync('app/JEPOTrackingDashboard.js','utf8');
assert.ok(dashboard.includes('jepoTrackingStatusLabel(r)'),'Display queue state rather than raw misleading PENDING.');
assert.ok(dashboard.includes('sortJepoActiveRecords(rows.filter'),'Group verified and unchecked shipments.');
assert.ok(dashboard.includes("['Awaiting First Check',awaiting]"));
assert.ok(dashboard.includes("['Retry Needed',retryNeeded]"));
assert.ok(dashboard.includes("tab!=='ACTIVE'||trackingStage==='ALL'"),'Do not accidentally hide Delivered AWBs.');
assert.ok(dashboard.includes('readOnly={')===false || dashboard.includes('readOnly'),'Preserve Haryana Admin read-only access.');
// A 30-day-old undelivered packet is still in Active; the 31st day is overdue.
const todayIst='2026-11-14';
const old={awb:'OLD',status:'IN_TRANSIT',bookingDate:'2026-10-01'};
const boundary={awb:'BOUNDARY',status:'PENDING',bookingDate:'2026-10-15'};
const oneDayOver={awb:'ONE',status:'PENDING',bookingDate:'2026-10-14'};
const deliveredOld={...old,awb:'DELIVERED',status:'DELIVERED'};
const datedDelivered={...old,awb:'DELIVERY_DATE',deliveredOn:'2026-11-13'};
const missingDate={awb:'MISSING',status:'PENDING',bookingDate:null};
assert.equal(jepoDaysSinceBooking('2026-10-14',todayIst),31);
assert.equal(jepoOverdueDays(oneDayOver,todayIst),1);
assert.equal(jepoOverdueDays(boundary,todayIst),null);
assert.equal(jepoOverdueDays(old,todayIst),14);
assert.equal(jepoOverdueDays(deliveredOld,todayIst),null);
assert.equal(jepoOverdueDays(datedDelivered,todayIst),null);
assert.equal(jepoOverdueDays(missingDate,todayIst),null);
assert.equal(jepoOverdueDays({bookingDate:'2026-02-30'},todayIst),null);
assert.equal(jepoTodayIst(new Date('2026-11-13T18:29:59Z')),'2026-11-13');
assert.equal(jepoTodayIst(new Date('2026-11-13T18:30:00Z')),'2026-11-14');
const source=[oneDayOver,old,boundary,deliveredOld,datedDelivered,missingDate];
assert.deepEqual(jepoOverdueRows(source,todayIst).map(r=>r.awb),['OLD','ONE']);
assert.equal(source.length,6,'Overdue is a view, not a duplicate or deletion');
assert.ok(dashboard.includes("['OVERDUE','Overdue – Not Delivered ('+overdue.length+')"));
assert.ok(dashboard.includes("tab==='OVERDUE'?overdue:active"));
assert.ok(dashboard.includes("['overdueDays','Overdue by (days)']"));
assert.ok(dashboard.includes("jepoOverdueDays(r,todayIst)"));
assert.ok(dashboard.includes("tab==='OVERDUE'?'jepo_overdue_not_delivered'"));
assert.ok(dashboard.includes("readOnly={")===false || dashboard.includes('readOnly'),'Preserve access');
console.log('JEPO overdue 31st-day, auto-delivered removal, IST midnight and export tab checks passed.');
const reportSample={awb:'JEPO123456',bookingDate:'2026-10-01',service:'FedEx',vendor:'ICL',
 consignee:'Example Customer',destination:'UK',goodsDescription:'Textbooks and clothes',
 weight:7.5,status:'IN_TRANSIT',liveStatus:'In Transit',liveRemarks:'Arrived at hub'};
const reportRows=overdueExportData([reportSample],'2026-11-14');
assert.ok(reportRows[0].includes('Goods Description'));
assert.ok(reportRows[0].includes('Days Overdue'));
assert.equal(reportRows[1][7],'Textbooks and clothes');
assert.equal(reportRows[1][10],44);
assert.equal(reportRows[1][11],14);
assert.ok(OVERDUE_EXPORT_COLUMNS.length>=13);
const pdfBytes=await createOverdueEditablePdfBytes([reportSample],'2026-11-14');
const loadedPdf=await PDFDocument.load(pdfBytes);
assert.equal(loadedPdf.getPageCount(),1);
const editableFields=loadedPdf.getForm().getFields();
assert.equal(editableFields.length,OVERDUE_EXPORT_COLUMNS.length);
assert.equal(loadedPdf.getForm().getTextField('r1_goodsDescription').getText(),'Textbooks and clothes');
assert.equal(loadedPdf.getForm().getTextField('r1_awb').getText(),'JEPO123456');
assert.equal(loadedPdf.getForm().getTextField('r1_overdueDays').getText(),'14');
const pdfSource=readFileSync('lib/jepoOverdueExports.js','utf8');
assert.ok(!pdfSource.includes('form.flatten('),'PDF cells must remain editable AcroForm fields.');
assert.ok(!pdfSource.includes("'MAYAVI'"),'No application branding in overdue report.');
assert.ok(dashboard.includes('Download Editable PDF'));
assert.ok(dashboard.includes('Download Excel'));
assert.ok(dashboard.includes('Goods Description'));
assert.ok(dashboard.includes('save_goods_description'));
console.log('JEPO branded-free editable overdue PDF form, goods descriptions, export fields and downloads passed.');
console.log('JEPO pending queue labels, retries, sort and filter regression passed.');
