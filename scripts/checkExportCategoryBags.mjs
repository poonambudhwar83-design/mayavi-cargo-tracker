import assert from 'node:assert/strict';
import {EXPORT_BAG_CODES,exportCategoryClientRate,exportCategorySummary,validateExportBagCount} from '../lib/exportCategoryBags.js';
import {auditExportIndex,exportAuditKey,exportAuditValues,exportManualCategoryCodes,mergeExportAuditBags} from '../lib/auditExportSync.js';
const result=exportCategorySummary({D:2,T:3,DT:1,GC:4});
assert.deepEqual(EXPORT_BAG_CODES,['D','T','DT','GC']);
assert.equal(result.clientCharge,2*10000+3*6000+1*6000+4*500);
assert.equal(result.deduction,2*6000+3*6000+1*6000+4*300);
assert.equal(result.netProfit,2*4000+3*0+1*0+4*200);
assert.equal(exportCategorySummary({}).netProfit,0);
assert.equal(exportCategoryClientRate('D','TPL'),10000);
assert.equal(exportCategoryClientRate('T','OVERSEAS'),6000);
assert.equal(exportCategoryClientRate('DT','DHL'),6000);
assert.equal(exportCategoryClientRate('GC','TPL'),300);
assert.equal(exportCategoryClientRate('GC','Overseas'),300);
assert.equal(exportCategoryClientRate('GC','DHL'),500);
assert.equal(exportCategoryClientRate('GC','M5'),500);
assert.equal(exportCategoryClientRate('GC','SHIPUNIV'),500);
assert.equal(exportCategorySummary({GC:5},'TPL').clientCharge,1500);
assert.equal(exportCategorySummary({GC:5},'OVERSEAS').deduction,1500);
assert.equal(exportCategorySummary({GC:5},'TPL').netProfit,0);
assert.equal(exportCategorySummary({GC:5},'OVERSEAS').netProfit,0);
assert.equal(exportCategorySummary({GC:5},'DHL').netProfit,1000);
assert.equal(exportCategorySummary({D:4},'TPL').clientCharge,40000);
assert.equal(exportCategorySummary({D:4},'TPL').deduction,24000); // existing deduction provisional

assert.equal(validateExportBagCount('0'),0);
assert.equal(validateExportBagCount('11'),11);
assert.equal(validateExportBagCount('2.5'),null);
assert.equal(validateExportBagCount('-1'),null);
assert.equal(validateExportBagCount('100001'),null);
// Excel-derived values never overwrite manually protected fields.
const audit={mawb:'098-12345678',client_name:'TPL',d:'2',t:'3',dt:'1',gc:'4',xray:'40',tray:'150',shift:'100',loader:'50',coLoader:'25'};
const auditValue=exportAuditValues(audit);
assert.deepEqual(auditValue.categoryBags,{D:2,T:3,DT:1,GC:4});
assert.equal(auditValue.shipmentCharge,null,'Any populated D/T/DT/G&C prevents Audit shipment charge.');
const shipmentOnly=exportAuditValues({...audit,d:'',t:'',dt:'',gc:''});
assert.equal(shipmentOnly.shipmentCharge,215,'Only X-ray + Shift + Loader + Co-loader; Tray excluded.');
assert.equal(exportAuditValues({...audit,d:'',t:'',dt:'',gc:'',co_loader:'70'}).shipmentCharge,260,'Real DB co_loader value is used.');
assert.equal(exportAuditValues({...audit,d:'',t:'',dt:'',gc:'',xray:'invalid'}).shipmentCharge,null,'Invalid charge is not imported.');
assert.equal(exportAuditValues({...audit,d:'0',t:'',dt:'',gc:''}).shipmentCharge,null,'Actual zero in category field is not blank.');
assert.equal(exportAuditValues({...audit,d:'',t:'',dt:'',gc:'',xray:'',shift:'',loader:'',co_loader:'',coLoader:''}).shipmentCharge,null,'No Audit money means no shipment charge.');
assert.equal(exportAuditKey('09812345678','  tPl  '),'09812345678|TPL');
assert.equal(exportAuditKey('09812345678',''),'', 'Never sync an unknown client.');
assert.notEqual(exportAuditKey('09812345678','TPL'),exportAuditKey('09812345678','DHL'), 'MAWB-only matches are forbidden.');
assert.notEqual(exportAuditKey('09812345678','TPL'),exportAuditKey('09812345679','TPL'), 'Client-only matches are forbidden.');
const index=auditExportIndex([audit,{...audit,client_name:'DIFFERENT',d:'99'}]);
assert.equal(index.get(exportAuditKey('09812345678','TPL')).d,'2');
assert.notEqual(index.get(exportAuditKey('09812345678','DIFFERENT')).d,'2');
assert.deepEqual(exportManualCategoryCodes({d_bags:7,manual_codes:null}),['D','T','DT','GC'],'Legacy saved rows must be protected.');
const legacy=mergeExportAuditBags({d_bags:7,t_bags:8,dt_bags:9,gc_bags:10,manual_codes:null},auditValue);
assert.deepEqual(legacy.categoryBags,{D:7,T:8,DT:9,GC:10});
const manual=mergeExportAuditBags({d_bags:99,t_bags:0,dt_bags:0,gc_bags:0,manual_codes:['D']},auditValue);
assert.deepEqual(manual.categoryBags,{D:99,T:3,DT:1,GC:4},'Only edited D stays locked; other fields remain auto.');
assert.deepEqual(manual.autoBagCodes,['T','DT','GC']);
const zero=mergeExportAuditBags({d_bags:0,t_bags:0,dt_bags:0,gc_bags:0,manual_codes:['D']},auditValue);
assert.equal(zero.categoryBags.D,0,'Manually set zero must not be overwritten.');
assert.deepEqual(mergeExportAuditBags(null,auditValue).categoryBags,auditValue.categoryBags);
console.log('Export Audit matching and charges conditional on blank categories; no fixed overrides; manual bag locks verified.');
